// Encodes the checksum-pinned, explicitly bounded zic output without applying
// timezone's first-transition sentinel filter. Run after build_timezone_source.py.
import 'dart:convert';
import 'dart:io';

import 'package:timezone/timezone.dart' as tz;
// The serializer is pinned to timezone 0.11.2 and checked by round-trip decode.
// ignore: implementation_imports
import 'package:timezone/src/tzdb.dart' as format;

void main() {
  final source = jsonDecode(
    File('.local/timezone-build/zones.json').readAsStringSync(),
  ) as Map<String, dynamic>;
  final db = tz.LocationDatabase();
  final zones = source['zones'] as Map<String, dynamic>;
  for (final entry in zones.entries) {
    final data = entry.value as Map<String, dynamic>;
    db.add(
      tz.Location(
        entry.key,
        [for (final s in data['times'] as List) (s as int) * 1000],
        (data['indices'] as List).cast<int>(),
        [
          for (final z in data['zones'] as List)
            tz.TimeZone(
              Duration(seconds: z[0] as int),
              isDst: z[1] as bool,
              abbreviation: z[2] as String,
            ),
        ],
      ),
    );
  }
  final bytes = format.tzdbSerialize(db);
  // Decode every emitted zone to ensure schema compatibility with the pin.
  if (format.tzdbDeserialize(bytes).length != zones.length) {
    throw StateError('Zone count changed');
  }
  final encoded = base64Encode(bytes);
  final output =
      StringBuffer(
          '// GENERATED by tool/encode_timezone_data.dart; do not edit.\n',
        )
        ..writeln(
          '// IANA ${source['iana']}; UTC padding [${source['start']}, ${source['end']}).',
        )
        ..writeln(
          "const boundedTimezoneVersion = 'iana-${source['iana']}/timezone-0.11.2/bounded-1970-2100/profile-2';",
        )
        ..writeln('const boundedTimezoneData =');
  for (var i = 0; i < encoded.length; i += 100) {
    output.writeln(
      "    '${encoded.substring(i, (i + 100).clamp(0, encoded.length))}'",
    );
  }
  output.writeln(';');
  File('packages/serverpod_calendar_core/lib/src/bounded_timezone_data.dart')
      .writeAsStringSync(output.toString());
  File('.local/timezone-build/bounded.tzf').writeAsBytesSync(bytes);
  final formatting = Process.runSync(Platform.resolvedExecutable, [
    'format',
    'packages/serverpod_calendar_core/lib/src/bounded_timezone_data.dart',
    'packages/serverpod_calendar_core/test/fixtures/timezone_profile_reference.dart',
  ]);
  if (formatting.exitCode != 0) throw StateError(formatting.stderr.toString());
  print('Encoded ${zones.length} zones, ${bytes.length} bytes');
}
