"""Build bounded TZif tables using the pinned IANA compiler (Linux/WSL).
Run from repository root. Archives are checksum verified before safe extraction.
The generated intermediate JSON is consumed by encode_timezone_data.dart.
"""
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import tarfile
import urllib.request
from datetime import datetime, timezone
from zoneinfo import ZoneInfo

VERSION = "2026e"
HASHES = {
    "tzcode": "cc3d27ca2a0d8399504551b920970d80af83bfb9c216e8082a15491921935d54",
    "tzdata": "b26882805f26aac59d5b222978e6580484b834ccdc98be89df2f05a6dc53a652",
}
# UTC padding resolves zone offsets at both civil profile boundaries.
START, END = -172800, 4102617600  # [1969-12-30, 2100-01-03)
FILES = ["africa", "antarctica", "asia", "australasia", "europe",
         "northamerica", "southamerica", "etcetera", "backward", "factory"]


def read_tzif(path):
    data = path.read_bytes()
    def header(pos):
        if data[pos:pos+4] != b"TZif":
            raise ValueError(f"Invalid TZif {path}")
        return struct.unpack_from(">6I", data, pos + 20)
    def size(c, width):
        gmt, std, leap, times, types, chars = c
        return times * (width+1) + types*6 + chars + leap*(width+4) + std + gmt
    c = header(0)
    pos = 44 + size(c, 4)
    c = header(pos)
    gmt, std, leap, count, types, chars = c
    pos += 44
    times = list(struct.unpack_from(f">{count}q", data, pos))
    pos += count*8
    indices = list(data[pos:pos+count]); pos += count
    records = [struct.unpack_from(">iBB", data, pos+i*6) for i in range(types)]
    pos += types*6
    names = data[pos:pos+chars]
    zones = [[offset, bool(dst), names[index:].split(b"\0", 1)[0].decode("ascii")]
             for offset, dst, index in records]
    if not times or times[0] != START or times[-1] != END:
        raise ValueError(f"Missing explicit calculation bounds for {path}")
    return {"times": times, "indices": indices, "zones": zones}


def main():
    root = Path.cwd()
    work = root / ".local/timezone-build"
    source, output = work / VERSION / "source", work / VERSION / "zones"
    source.mkdir(parents=True, exist_ok=True)
    output.mkdir(parents=True, exist_ok=True)
    for kind, expected in HASHES.items():
        archive = work / f"{kind}{VERSION}.tar.gz"
        if not archive.exists():
            urllib.request.urlretrieve(f"https://data.iana.org/time-zones/releases/{archive.name}", archive)
        if hashlib.sha256(archive.read_bytes()).hexdigest() != expected:
            raise ValueError(f"Checksum mismatch: {archive.name}")
        with tarfile.open(archive) as tar:
            # IANA archives contain top-level regular source files only.
            for member in tar.getmembers():
                if not member.isfile() or Path(member.name).name != member.name:
                    raise ValueError(f"Unexpected archive member: {member.name}")
            tar.extractall(source)
    subprocess.run(["make", "zic"], cwd=source, check=True)
    subprocess.run([str(source / "zic"), "-b", "fat", "-r", f"@{START}/@{END}",
                    "-d", str(output), *FILES], cwd=source, check=True)
    tables = {p.relative_to(output).as_posix(): read_tzif(p)
              for p in sorted(output.rglob("*")) if p.is_file()}
    result = {"iana": VERSION, "start": START, "end": END, "zones": tables}
    (work / "zones.json").write_text(json.dumps(result, separators=(",", ":")), encoding="utf-8")
    # Independent stdlib TZif reader validates the runtime decoder against zic.
    samples = [int(datetime(y,m,3,12,tzinfo=timezone.utc).timestamp())
               for y in range(1970,2100) for m in (1,7)]
    digest = 0
    names = []
    for name, table in tables.items():
        if not any(z[2] != "-00" for z in table["zones"]):
            continue
        names.append(name)
        with (output/name).open("rb") as stream:
            zone = ZoneInfo.from_file(stream)
        for instant in samples:
            local = datetime.fromtimestamp(instant,timezone.utc).astimezone(zone)
            offset = "unknown" if local.tzname() == "-00" else int(local.utcoffset().total_seconds())
            for char in f"{name}:{instant}:{offset};":
                digest = (digest*65599+ord(char))%2147483647
    fixture = root/"packages/serverpod_calendar_core/test/fixtures/timezone_profile_reference.dart"
    fixture.parent.mkdir(exist_ok=True)
    fixture.write_text("// GENERATED by tool/build_timezone_source.py using Python zoneinfo.\n"
                       +f"const referenceZoneCount = {len(names)};\nconst referenceDigest = {digest};\n"
                       +f"const referenceInstants = {samples};\n",encoding="utf-8")
    print(f"Generated {len(tables)} bounded zones; independent oracle {len(names)*len(samples)} samples, digest {digest}")


if __name__ == "__main__":
    main()
